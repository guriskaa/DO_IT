# Project: GrantTracker
class GrantTracker:
    """GrantTracker: Трекер грантов с заявками, дедлайнами, документами, статусами и бюджетом.

    Сценарии использования:
        1. Регистрация: новый пользователь создаёт аккаунт и вводит email, пароль и имя.
        2. Создание заявки: пользователь заполняет форму заявки — название, описание, бюджет, приоритет,
           дедлайн, категорию и загружает документы (PDF, DOCX, PNG, JPG).
        3. Управление заявками: просмотр списка заявок с фильтрацией по статусу, приоритету, дедлайну;
           обновление статуса (draft, pending, approved, rejected, completed); удаление заявки.
        4. Бюджетирование: просмотр бюджета заявки, сравнение с фактическими расходами,
           автоматическое уведомление о превышении бюджета.
        5. Дедлайны: просмотр ближайших дедлайнов, напоминания за 7 дней до дедлайна,
           сортировка заявок по дедлайну.
        6. Документация: загрузка, просмотр и удаление документов; проверка типов файлов.
        7. Статистика: сводка по статусам заявок, распределение по категориям,
           анализ бюджета по заявкам.
        8. Уведомления: email-уведомления о новых заявках, изменении статуса, приближении дедлайна,
           превышении бюджета.
        9. Поиск: поиск заявок по названию, описанию, категории, статусу.
        10. Экспорт: экспорт данных заявки в JSON и CSV.

    Аргументы:
        grant_name: str — название заявки.
        description: str — описание заявки.
        budget: float — бюджет заявки.
        priority: str — приоритет заявки (low, medium, high).
        deadline: str — дедлайн заявки (YYYY-MM-DD).
        category: str — категория заявки.
        documents: list[str] — список путей к документам.
        email: str — email пользователя.
        password: str — пароль пользователя.
        name: str — имя пользователя.
        status: str — статус заявки (draft, pending, approved, rejected, completed).
    """
